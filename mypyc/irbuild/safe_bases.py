"""Standard library classes that native classes can inherit from.

Stubs don't describe the instance layout of a class, and a class implemented
in C may have instance fields that native attributes would overlap. So a native
class can only inherit from a non-mypyc class defined in a stub if the class is
listed here (see find_unsupported_base in prepare.py).

The list only covers classes that are commonly used as base classes in
practice, to keep it short and maintainable:

- used as a base class in at least two of the 1000 most downloaded PyPI
  projects, in a large private codebase (surveyed in November 2026), or in
  mypy itself,
- documented in the CPython docs, and
- with the instance layout of object (or BaseException) on Python 3.10 to 3.14
  (including the free-threaded build) and on 3.15, wherever the class exists,
  checked at runtime. Native subclasses were also compiled and tested.

Names are the full names mypy uses, i.e. those of the modules where typeshed
defines the classes, which aren't always the public modules (for example,
asyncio.Protocol is asyncio.protocols.Protocol). Where the stubs define a class
in a different place on some Python version, both names are listed.

Classes only available on Python 3.10 and 3.11 are left out. The Windows definitions
of asyncio.SelectorEventLoop and asyncio.DefaultEventLoopPolicy were added based on
the CPython sources, since their Unix equivalents are on the list.
"""

